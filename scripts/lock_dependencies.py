"""Resolve the requirements and emit a hash-locked file for the CI runner.

Some packages (notably pyaes) ship only an sdist, so resolve in two stages:
1. one interpreter-independent resolution for both runtime and development tools;
2. one exact-artefact lookup per resolved version for Linux x86_64/cp311.

Usage:
    python scripts/lock_dependencies.py
    python scripts/lock_dependencies.py --check   # CI gate: fail on drift
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pip(*arguments: str, report: Path) -> dict:
    command = [
        sys.executable,
        "-m",
        "pip",
        "install",
        "--dry-run",
        "--ignore-installed",
        "--target",
        str(report.parent / "unmanaged-target"),
        "--report",
        str(report),
        "--quiet",
        *arguments,
    ]
    subprocess.run(command, cwd=ROOT, check=True)
    return json.loads(report.read_text(encoding="utf-8"))


def build_lock() -> str:
    with tempfile.TemporaryDirectory() as directory:
        base = Path(directory)
        host = pip("-r", "requirements-dev.txt", report=base / "host.json")
        entries = []
        for index, item in enumerate(sorted(host["install"], key=lambda it: it["metadata"]["name"].lower())):
            metadata = item["metadata"]
            target = base / f"target-{index}.json"
            resolution = pip(
                f"{metadata['name']}=={metadata['version']}",
                "--no-deps",
                "--platform",
                "manylinux2014_x86_64",
                "--python-version",
                "3.11",
                "--implementation",
                "cp",
                "--abi",
                "cp311",
                report=target,
            )
            archive = resolution["install"][0]["download_info"]["archive_info"]
            digest = archive["hash"] if isinstance(archive.get("hash"), str) else archive.get("hash", {}).get("sha256", "")
            if digest.startswith("sha256"):
                digest = digest.removeprefix("sha256").lstrip(":=")
            if not digest:
                raise RuntimeError(f"no sha256 for {metadata['name']}=={metadata['version']}")
            entries.append((metadata["name"], metadata["version"], digest))

    lines = ["# Generated by scripts/lock_dependencies.py; Linux x86_64 / CPython 3.11."]
    for name, version, digest in entries:
        lines.extend([f"{name}=={version} \\", f"    --hash=sha256:{digest}"])
    return "\n".join(lines) + "\n"


def main() -> None:
    expected = build_lock()
    output = ROOT / "requirements.lock"
    if "--check" in sys.argv[1:]:
        actual = output.read_text(encoding="utf-8")
        if actual != expected:
            raise SystemExit("requirements.lock is out of date; run `python scripts/lock_dependencies.py`")
        print(f"requirements.lock is in sync ({len(expected.splitlines())} lines)")
        return
    output.write_text(expected, encoding="utf-8")
    print(f"wrote {output.relative_to(ROOT)} ({len(expected.splitlines())} lines)")


if __name__ == "__main__":
    main()
